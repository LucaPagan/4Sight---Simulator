"""Generate the TypeScript subset used by the app from Pydantic's JSON Schema."""

import json
from pathlib import Path

from pydantic import BaseModel

from .contracts import AgePrediction, ConsumerProfile, Prediction, SimulationRun
from .schemas import AgentEvaluation, CampaignBrief, RuntimeSelection


def typescript(node):
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(x) for x in node["enum"])
    if "anyOf" in node:
        return " | ".join(typescript(x) for x in node["anyOf"])
    kind = node.get("type")
    if kind == "array":
        return f"Array<{typescript(node['items'])}>"
    if kind == "object":
        required = node.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(k)}{'' if k in required else '?'}: {typescript(v)}"
                for k, v in node.get("properties", {}).items()
            )
            + " }"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate_contracts(root: Path = Path(".")) -> None:
    models: list[type[BaseModel]] = [
        CampaignBrief,
        AgentEvaluation,
        AgePrediction,
        ConsumerProfile,
        Prediction,
        SimulationRun,
        RuntimeSelection,
    ]
    schemas = {}
    for model in models:
        schema = model.model_json_schema()
        schemas.update(schema.pop("$defs", {}))
        schemas[model.__name__] = schema
    (root / "docs/contracts.json").write_text(json.dumps(schemas, ensure_ascii=False, indent=2) + "\n")
    (root / "frontend/lib/contracts.generated.ts").write_text(
        "// Generated by audience schemas. Do not edit.\n"
        + "\n".join(f"export type {name} = {typescript(schema)};" for name, schema in schemas.items())
        + "\n"
    )
