"""Resumable native benchmark with immutable common inputs and an isolated SQLite cache."""

import httpx

from .agents import policy_key
from .decision_quality import assess_decisions, export_rubric
from .performance import stage_metrics
from .persona_cards import PERSONA_PROMPT_VERSION, PersonaWriter, skeleton_view, template_card
from .reaction_execution import run_reaction_plan
from .reactions import REACTION_PROMPT_VERSION, reaction_plan
from .repository import ArtifactStore, Repository
from .schemas import CampaignBrief
from .stimulus_view import SLOTS


def benchmark_native(service, scenario_id, provider, model=None, concurrency=1, *, client=None):
    if not 1 <= concurrency <= 4:
        raise ValueError("Concorrenza da 1 a 4")
    if provider in {"gemini", "cloudflare"} and concurrency != 1:
        raise ValueError("Il benchmark cloud richiede concorrenza 1")
    scenario = service.repo.get("scenarios", scenario_id)
    population = service.repo.get("populations", scenario["population_id"])
    brief = CampaignBrief.model_validate(scenario["brief"])
    if len(population["profiles"]) < 20 or len(brief.creatives) < 2:
        raise ValueError("Servono almeno 20 profili e due creatività")
    if any("household" not in p for p in population["profiles"]):
        raise ValueError("Il benchmark native richiede un pubblico mirato")
    client = client or service.client(provider, model)
    runtime = client.status()
    if not runtime["ready"]:
        raise ValueError(runtime.get("error") or "Provider non disponibile")
    brief = brief.model_copy(update={"creatives": brief.creatives[:2], "date_to": brief.date_from})
    profiles = sorted(
        population["profiles"], key=lambda p: policy_key({"seed": brief.seed, "profile": skeleton_view(p)})
    )[:20]
    fixture_input = {
        "brief": brief.model_dump(mode="json"),
        "profiles": profiles,
        "version": "native-benchmark-v1",
    }
    fixture_id = policy_key(fixture_input)
    store = ArtifactStore(service.cfg.artifact_dir / "benchmarks")
    fixture_path = f"native-fixtures/{fixture_id}.json"
    if store.path(fixture_path).exists():
        fixture = store.read_json(fixture_path)
        if (
            fixture["input"] != fixture_input
            or policy_key(fixture["reference_cards"]) != fixture["reference_hash"]
        ):
            raise ValueError("Fixture benchmark modificata: confronto non valido")
    else:
        # Reference cards are frozen once, never generated by the model currently being measured.
        existing = population.get("cards", {})
        reference = {
            p["agent_id"]: existing.get(p["agent_id"])
            or {**template_card(p, i + 1), "facts": [], "source": "template"}
            for i, p in enumerate(profiles)
        }
        from .persona_cards import describe_profile

        for p in profiles:
            reference[p["agent_id"]] = {**reference[p["agent_id"]], "facts": describe_profile(p)}
        fixture = {
            "input": fixture_input,
            "reference_cards": reference,
            "reference_hash": policy_key(reference),
        }
        store.write_json(fixture_path, fixture)
    config = {
        "fixture_hash": fixture_id,
        "reference_hash": fixture["reference_hash"],
        "provider": provider,
        "model": client.model,
        "digest": runtime["digest"],
        "writer_version": PERSONA_PROMPT_VERSION,
        "reaction_version": REACTION_PROMPT_VERSION,
        "concurrency": concurrency,
        "card_batch_size": getattr(client, "card_batch_size", 8),
    }
    folder = f"native/{fixture_id}/{policy_key(config)}"
    checkpoint_path = f"{folder}/report.json"
    if store.path(checkpoint_path).exists():
        report = store.read_json(checkpoint_path)
        if report["config"] != config:
            raise ValueError("Configurazione benchmark incompatibile")
        if report["status"] == "complete":
            return report
    else:
        report = {
            "config": config,
            "fixture_hash": fixture_id,
            "reference_hash": fixture["reference_hash"],
            "cases": 120,
            "status": "partial",
            "qualified": False,
            "human_review_status": "pending",
            "cold": {"cards": stage_metrics(), "reactions": stage_metrics()},
            "writer_state": {},
            "reference_sources": {
                p["agent_id"]: fixture["reference_cards"][p["agent_id"]].get("source") for p in profiles
            },
            "warning": "Validità tecnica e velocità non dimostrano realismo o accuratezza predittiva.",
        }
    repo = Repository(f"sqlite:///{store.path(folder)}/cache.sqlite")
    writer = PersonaWriter(repo, client, runtime["digest"], brief.vertical, brief.country, brief.brand)

    def card_progress(done, total):
        report["cold"]["cards"] = dict(writer.performance)
        report["cards_completed"] = done
        store.write_json(checkpoint_path, report)

    def reaction_progress(completed, metrics):
        report["cold"]["reactions"] = dict(metrics)
        report["reactions_completed"] = len(completed)
        store.write_json(checkpoint_path, report)

    try:
        try:
            cards, persona_report = writer.write(
                profiles,
                progress=card_progress,
                performance=report["cold"]["cards"],
                state=report["writer_state"],
            )
            report["persona_report"] = persona_report
            work = reaction_plan(brief, profiles, fixture["reference_cards"], runtime["digest"], slots=SLOTS)
            execution = run_reaction_plan(
                repo,
                client,
                work,
                runtime["digest"],
                concurrency=concurrency,
                performance=report["cold"]["reactions"],
                progress=reaction_progress,
                max_evaluations=service.cfg.max_evaluations,
            )
            if execution["error"]:
                raise execution["error"]
            if len(execution["decisions"]) != 120:
                raise ValueError("Copertura benchmark incompleta")
        except (ValueError, httpx.HTTPError) as exc:
            report["error"] = f"{type(exc).__name__}: {str(exc)[:300]}"
            store.write_json(checkpoint_path, report)
            return report
        warm_writer = PersonaWriter(
            repo, client, runtime["digest"], brief.vertical, brief.country, brief.brand
        )
        warm_writer.write(profiles)
        warm = run_reaction_plan(repo, client, work, runtime["digest"], concurrency=concurrency)
        report["cached"] = {"cards": dict(warm_writer.performance), "reactions": warm["performance"]}
        records = [{**item, "decision": execution["decisions"][item["key"]]["decision"]} for item in work]
        report["quality"] = assess_decisions(records, {p["agent_id"]: p for p in profiles})
        report["decisions"] = records
        rubric = export_rubric(records, n=60, seed=brief.seed)
        store.write_bytes(f"{folder}/rubric.csv", rubric.pop("csv").encode(), "text/csv")
        store.write_json(f"{folder}/rubric-key.json", rubric)
        report["rubric_path"] = str(store.path(f"{folder}/rubric.csv"))
        report["report_path"] = str(store.path(checkpoint_path))
        report["status"] = "complete"
        report.pop("error", None)
        elapsed = sum(report["cold"][stage]["seconds"] for stage in ("cards", "reactions"))
        valid = sum(c["source"] == "llm" for c in cards.values()) + len(records)
        report["valid_results_per_minute"] = valid * 60 / elapsed if elapsed else None
        report["fallback"] = sum(c["source"] == "template" for c in cards.values())
        store.write_json(checkpoint_path, report)
        return report
    finally:
        repo.engine.dispose()
